// Bake the free Downtown City MegaKit examples with their glTF PBR materials.
// Texture resizing uses macOS sips; originals remain available beside the models.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { Box3, Vector3 } from 'three';
import { GLTFLoader } from '../node_modules/three/examples/jsm/loaders/GLTFLoader.js';
const root=new URL('../assets/downtown/',import.meta.url),models={},materials={},textures={};
await mkdir(new URL('optimized/',root),{recursive:true});
globalThis.ProgressEvent??=class ProgressEvent {constructor(type,props){Object.assign(this,{type},props);}};
function packAttribute(attribute){
  const array=attribute.array;
  return {array:Buffer.from(array.buffer,array.byteOffset,array.byteLength).toString('base64'),type:array.constructor.name,itemSize:attribute.itemSize,normalized:attribute.normalized};
}
function packGeometry(geometry){
  return {packed:true,attributes:Object.fromEntries(Object.entries(geometry.attributes).map(([key,value])=>[key,packAttribute(value)])),index:geometry.index?packAttribute(geometry.index):null,groups:geometry.groups};
}
for(const name of ['Building_Small_1','Building_Medium_2_001','Building_Large_2','Street_2Lane','Street_4WayIntersection']){
  const json=JSON.parse(await readFile(new URL(name+'.gltf',root),'utf8'));
  async function texture(info){
    if(!info)return null;
    const source=json.textures[info.index],image=json.images[source.source],key='downtown:'+image.uri;
    if(!textures[key]){
      const color=/BaseColor|interior/.test(image.uri),size=/_ORM/.test(image.uri)?512:1024;
      const output=new URL('optimized/'+image.uri.replace(/\.png$/,color?'.jpg':'.png'),root);
      execFileSync('sips',['-Z',String(size),'-s','format',color?'jpeg':'png',...(color?['-s','formatOptions','85']:[]),fileURLToPath(new URL(image.uri,root)),'--out',fileURLToPath(output)],{stdio:'ignore'});
      textures[key]='data:image/'+(color?'jpeg':'png')+';base64,'+(await readFile(output)).toString('base64');
    }
    const sampler=json.samplers?.[source.sampler]||{};
    if(info.extensions?.KHR_texture_transform)throw new Error('Texture transforms need explicit support');
    return {key,channel:info.texCoord||0,wrapS:sampler.wrapS??10497,wrapT:sampler.wrapT??10497};
  }
  for(const source of json.materials){
    const key='downtown:'+source.name,pbr=source.pbrMetallicRoughness||{};
    const definition={pbr:true,color:pbr.baseColorFactor||[1,1,1,1],metalness:pbr.metallicFactor??1,roughness:pbr.roughnessFactor??1,
      base:await texture(pbr.baseColorTexture),normal:await texture(source.normalTexture),orm:await texture(pbr.metallicRoughnessTexture),ao:await texture(source.occlusionTexture),
      normalScale:source.normalTexture?.scale??1,aoIntensity:source.occlusionTexture?.strength??1,
      transparent:source.alphaMode==='BLEND',alphaTest:source.alphaMode==='MASK'?(source.alphaCutoff??.5):0,doubleSided:!!source.doubleSided};
    if(materials[key]&&JSON.stringify(materials[key])!==JSON.stringify(definition))throw new Error('Conflicting material '+key);
    materials[key]=definition;
    delete pbr.baseColorTexture;delete pbr.metallicRoughnessTexture;delete source.normalTexture;delete source.occlusionTexture;
  }
  for(const buffer of json.buffers)buffer.uri='data:application/octet-stream;base64,'+(await readFile(new URL(buffer.uri,root))).toString('base64');
  delete json.images;delete json.textures;
  const {scene}=await new GLTFLoader().parseAsync(JSON.stringify(json),'');scene.updateMatrixWorld(true);
  const bounds=new Box3().setFromObject(scene),center=bounds.getCenter(new Vector3()),meshes=[],keys=[];
  scene.traverse(mesh=>{
    if(!mesh.isMesh)return;
    const geometry=mesh.geometry.clone().applyMatrix4(mesh.matrixWorld);geometry.translate(-center.x,-bounds.min.y,-center.z);
    // In this kit vertex colors encode wear for engine-specific shaders, not diffuse tint.
    geometry.deleteAttribute('color');
    meshes.push(packGeometry(geometry));keys.push('downtown:'+mesh.material.name);
  });
  models[name]={meshes,materials:keys,namespace:'downtown',size:bounds.getSize(new Vector3()).toArray(),ground:name.startsWith('Street_')};
  console.log(name,models[name].size,'meshes',meshes.length);
}
await writeFile(new URL('../src/downtown-asset.js',import.meta.url),'// Generated by scripts/prepare-downtown.mjs. Quaternius CC0; see assets/downtown/License_Standard.txt.\nexport default '+JSON.stringify({models,materials,textures})+';\n');
