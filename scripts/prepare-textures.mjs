// Pack the CC0 photo textures (Poly Haven + ambientCG, see assets/textures)
// into a base64 ES module so the standalone HTML stays fully offline.
// Sources: Poly Haven clay_plaster / yellow_bricks / large_sandstone_blocks,
// ambientCG Plaster001 / Ground054 / Grass003 / Wood026 / Concrete034 (all CC0).
import { readFile, writeFile } from 'node:fs/promises';

const root=new URL('../assets/textures/',import.meta.url);
const sets={
  clay:['clay-plaster'],plaster:['plaster'],'yellowBricks':['yellow-bricks'],
  sandstoneBlocks:['sandstone-blocks'],sandGround:['sand-ground'],grass:['grass'],
  wood:['wood'],concrete:['concrete'],
};
const out={};
for(const [key,[base]] of Object.entries(sets)){
  out[key]={
    map:'data:image/jpeg;base64,'+(await readFile(new URL(base+'-diff.jpg',root))).toString('base64'),
    normal:'data:image/jpeg;base64,'+(await readFile(new URL(base+'-nor.jpg',root))).toString('base64'),
  };
}
const js='// Generated by scripts/prepare-textures.mjs. CC0 photo textures (Poly Haven / ambientCG).\nexport default '+JSON.stringify(out)+';\n';
await writeFile(new URL('../src/textures-asset.js',import.meta.url),js);
console.log('src/textures-asset.js written:',(js.length/1048576).toFixed(2),'MB,',Object.keys(out).length,'sets');
