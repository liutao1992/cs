// Bake selected Kenney GLBs into synchronous, offline-ready geometry.
import { readFile, writeFile } from 'node:fs/promises';
import { GLTFLoader } from '../node_modules/three/examples/jsm/loaders/GLTFLoader.js';
import { Box3, Vector3 } from 'three';
const pack=process.argv[2]||'suburban';
if(!['suburban','modular'].includes(pack))throw new Error('Expected suburban or modular');
const root=new URL('../assets/'+pack+'/',import.meta.url);
const names=pack==='modular'?['building-sample-house-a','building-sample-house-c','building-sample-tower-a','building-sample-tower-d']:['building-type-a','building-type-c','building-type-f','tree-large','road-straight','road-crossroad'];
const models={};
// Node has no DOM image loader; keep the atlas separately for browser loading.
globalThis.ProgressEvent??=class ProgressEvent { constructor(type,props){Object.assign(this,{type},props);} };
for(const name of names){
  const file=await readFile(new URL(name+'.glb',root));
  const length=file.readUInt32LE(12),json=JSON.parse(file.subarray(20,20+length).toString());
  const binary=file.subarray(28+length);
  json.buffers[0].uri='data:application/octet-stream;base64,'+binary.toString('base64');
  for(const mat of json.materials)delete mat.pbrMetallicRoughness.baseColorTexture;
  delete json.images;delete json.textures;
  const {scene}=await new GLTFLoader().parseAsync(JSON.stringify(json),'');
  scene.updateMatrixWorld(true);
  const bounds=new Box3().setFromObject(scene),center=bounds.getCenter(new Vector3());
  const meshes=[];
  scene.traverse(mesh=>{
    if(!mesh.isMesh)return;
    const geometry=mesh.geometry.clone().applyMatrix4(mesh.matrixWorld);
    geometry.translate(-center.x,-bounds.min.y,-center.z);
    meshes.push(geometry.toJSON());
  });
  models[name]={meshes,size:bounds.getSize(new Vector3()).toArray(),atlas:name.startsWith('road-')?'roads':pack};
  console.log(name,models[name].size);
}
const textures={};
for(const name of pack==='modular'?['modular']:['suburban','roads'])textures[name]='data:image/png;base64,'+(await readFile(new URL(name+'.png',root))).toString('base64');
await writeFile(new URL('../src/'+pack+'-asset.js',import.meta.url),'// Generated by scripts/prepare-suburban.mjs '+pack+'. Kenney, CC0.\nexport default '+JSON.stringify({models,textures})+';\n');
